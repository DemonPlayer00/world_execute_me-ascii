def ink_tiny(text: str) -> list[list[bool]]:
    """3x5 glyphs packed edge to edge."""
    width = len(text) * TINY_W
    rows = [[False] * width for _ in range(TINY_H)]
    for i, ch in enumerate(text.upper()):
        g = TINY.get(ch, TINY[" "])
        for y in range(TINY_H):
            row = rows[y]
            for gx in range(TINY_W):
                if g[y][gx] == "#":
                    row[i * TINY_W + gx] = True
    return rows


def measure_tiny(text: str, gap: int = 1) -> tuple[int, int]:
    if not text:
        return 0, 0
    return len(text) * (TINY_W + gap) - gap, TINY_H


def condense_tiny(text: str, max_w: int, gap: int = 1) -> str:
    out = text
    while out and measure_tiny(out, gap)[0] > max_w:
        out = out[:-1]
    return out

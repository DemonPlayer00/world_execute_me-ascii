GLYPH_W = 5
GLYPH_H = 7


def gap_cells(scale: int = 1) -> int:
    """Gap between glyphs, measured in *screen cells*.

    The bitmap is point-scaled, so a one-pixel bitmap gap would become four
    columns at scale 4 -- enough to push a word off a wide screen.  Spacing is
    therefore applied after scaling, not before."""
    return max(1, min(3, scale // 2))

# characters we can silently widen/shrink when a line will not fit
_SUBSTITUTE = {",": " ", "'": "", '"': "", "!": "", "?": "", ".": "", ":": ""}


def ink_char(ch: str) -> list[list[bool]]:
    """One glyph, 5x7, as bools."""
    g = GLYPHS.get(ch.upper(), GLYPHS[" "])
    return [[c == "#" for c in row] for row in g]


def ink(text: str) -> list[list[bool]]:
    """Glyphs packed edge to edge; spacing is applied at draw time."""
    width = len(text) * GLYPH_W
    rows = [[False] * width for _ in range(GLYPH_H)]
    for i, ch in enumerate(text.upper()):
        g = GLYPHS.get(ch, GLYPHS[" "])
        for y in range(GLYPH_H):
            row = rows[y]
            for gx in range(GLYPH_W):
                if g[y][gx] == "#":
                    row[i * GLYPH_W + gx] = True
    return rows


def measure(text: str, scale: int = 1) -> tuple[int, int]:
    """Width/height in character cells of `text` rendered at `scale`."""
    if not text:
        return 0, 0
    return (len(text) * GLYPH_W * scale
            + max(0, len(text) - 1) * gap_cells(scale)), GLYPH_H * scale


def fit_scale(text: str, max_w: int, max_h: int = 7 * 4) -> int:
    """Largest integer scale whose bitmap still fits the given box."""
    if not text:
        return 1
    s = 1
    for cand in range(2, 9):
        if measure(text, cand)[0] <= max_w and GLYPH_H * cand <= max_h:
            s = cand
        else:
            break
    return max(1, s)


def condense(text: str, max_w: int) -> str:
    """Shorten a caption until its bitmap fits `max_w` cells at scale 1."""
    if measure(text)[0] <= max_w:
        return text
    out = text
    while out and measure(out)[0] > max_w:
        out = out[:-1]
    while out and out[-1] in _SUBSTITUTE:
        out = out[:-1]
    return out


